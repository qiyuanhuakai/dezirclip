"""Generate protocol values, settings metadata and an offline schema."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def pascal(value):
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[._-]", value))


def type_of(schema, language):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if language == "rust" and "x-rust-type" in schema:
        return schema["x-rust-type"]
    kind = schema.get("type")
    if isinstance(kind, list):
        inner = type_of({**schema, "type": next(x for x in kind if x != "null")}, language)
        return "Option<" + inner + ">" if language == "rust" else "*" + inner
    if kind == "array":
        inner = type_of(schema["items"], language)
        return "Vec<" + inner + ">" if language == "rust" else "[]" + inner
    if kind == "integer":
        native = schema.get("x-rust-type", "i64")
        return {"u16": "uint16", "u32": "uint32", "u64": "uint64", "i64": "int64"}.get(native, "int64")
    return ({"string": "String", "boolean": "bool", "number": "f64"}.get(kind, "serde_json::Value")
            if language == "rust" else {"string": "string", "boolean": "bool", "number": "float64"}.get(kind, "json.RawMessage"))


def settings_outputs(groups):
    rust = [
        "// Generated by scripts/generate-protocol.py; edit protocol/settings.catalog.json.",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct Setting {",
        "    pub key: &'static str,",
        "    pub group: &'static str,",
        "    pub kind: &'static str,",
        "    pub values: &'static [&'static str],",
        "    pub label_key: &'static str,",
        "    pub requires_restart: bool,",
        "    pub seed_default: Option<&'static str>,",
        "}", "",
    ]
    go = [
        "// Code generated by scripts/generate-protocol.py. Edit protocol/settings.catalog.json.",
        "package protocol", "",
        "type Setting struct {",
        "\tKey             string",
        "\tGroup           string",
        "\tKind            string",
        "\tValues          []string",
        "\tLabelKey        string",
        "\tRequiresRestart bool",
        "\tSeedDefault     *string",
        "}", "",
    ]
    ts = ["// Generated by scripts/generate-protocol.py; edit protocol/settings.catalog.json."]
    seen = set()
    for group, entries in groups.items():
        for entry in entries:
            key = entry["key"]
            label = entry["labelKey"]
            kind = entry["kind"]
            values = entry.get("values", [])
            restart = entry["requiresRestart"]
            seed = entry.get("seedDefault")
            if key in seen or not re.fullmatch(r"app\.[a-z][a-z0-9_]*", key):
                raise ValueError(f"invalid or duplicate setting key: {key}")
            if not re.fullmatch(r"[a-z][a-z0-9_]*", label) or type(restart) is not bool:
                raise ValueError(f"invalid setting label or restart policy: {key}")
            if kind == "boolean" and not values:
                allowed = ("true", "false")
            elif kind == "enum" and values and all(isinstance(value, str) for value in values):
                allowed = values
            else:
                raise ValueError(f"invalid logical type or choices: {key}")
            if seed is not None and seed not in allowed:
                raise ValueError(f"invalid persisted default: {key}")
            seen.add(key)
            stem = key.removeprefix("app.")
            rust_name = stem.upper()
            go_name = pascal(stem)
            ts_name = go_name[0].lower() + go_name[1:] + "Setting"
            value_literals = ", ".join(json.dumps(value) for value in values)
            rust_seed = "None" if seed is None else f"Some({json.dumps(seed)})"
            rust += [
                f"pub const {rust_name}: Setting = Setting {{",
                f"    key: {json.dumps(key)},",
                f"    group: {json.dumps(group)},",
                f"    kind: {json.dumps(kind)},",
                f"    values: &[{value_literals}],",
                f"    label_key: {json.dumps(label)},",
                f"    requires_restart: {json.dumps(restart)},",
                f"    seed_default: {rust_seed},",
                "};", "",
            ]
            go += [
                f"const Setting{go_name} = {json.dumps(key)}",
                f"const Setting{go_name}Label = {json.dumps(label)}", "",
                f"func {go_name}Setting() Setting {{",
            ]
            if seed is not None:
                go.append(f"\tseed := {json.dumps(seed)}")
            go += [
                "\treturn Setting{",
                f"\t\tKey:             Setting{go_name},",
                f"\t\tGroup:           {json.dumps(group)},",
                f"\t\tKind:            {json.dumps(kind)},",
                f"\t\tValues:          " + ("nil," if not values else f"[]string{{{value_literals}}},"),
                f"\t\tLabelKey:        Setting{go_name}Label,",
                f"\t\tRequiresRestart: {json.dumps(restart)},",
                "\t\tSeedDefault:     " + ("nil," if seed is None else "&seed,"),
                "\t}", "}", "",
            ]
            ts.append(f"export const {ts_name} = {json.dumps({**entry, 'group': group}, indent=4)} as const;")
    return {
        ROOT / "crates/dzc-protocol/src/settings.rs": "\n".join(rust),
        ROOT / "clients/go/protocol/settings.go": "\n".join(go),
        ROOT / "src/shared/protocol/settings.ts": "\n".join(ts) + "\n",
    }


def outputs():
    definitions = {}
    documents = []
    settings = json.loads((ROOT / "protocol/settings.catalog.json").read_text(encoding="utf-8"))
    metadata = settings_outputs(settings)
    for path in sorted((ROOT / "protocol/schema").glob("*.schema.json")):
        document = json.loads(path.read_text(encoding="utf-8"))
        documents.append(document)
        for name, schema in document["$defs"].items():
            if name in definitions:
                raise ValueError("duplicate protocol definition: " + name)
            definitions[name] = schema

    def local_refs(value):
        if isinstance(value, dict):
            result = {}
            for key, child in value.items():
                if key == "$ref":
                    if not child.startswith("https://dezirclip.local/protocol/v1/") or "#/$defs/" not in child:
                        raise ValueError("nonlocal protocol reference: " + child)
                    target = child.rsplit("/", 1)[1]
                    if target not in definitions:
                        raise ValueError("unknown protocol definition: " + target)
                    result[key] = "#/$defs/" + target
                elif key == "x-settings-catalog-keys":
                    if "enum" not in value:
                        raise ValueError("settings catalog requires a schema enum")
                elif key == "enum" and "x-settings-catalog-keys" in value:
                    registered = [entry["key"] for entry in settings[value["x-settings-catalog-keys"]]]
                    if set(registered).intersection(child):
                        raise ValueError("catalog setting is also registered directly in the schema")
                    result[key] = child + registered
                else:
                    result[key] = local_refs(child)
            return result
        if isinstance(value, list):
            return [local_refs(child) for child in value]
        return value

    envelope = next(doc for doc in documents if doc["$id"].endswith("/envelope.schema.json"))
    bundle = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": local_refs(definitions)}
    rust = ["// Generated by scripts/generate-protocol.py; edit protocol/schema instead.",
            "use serde::{Deserialize, Serialize};", "",
            f"pub const MAX_FRAME_BYTES: usize = {envelope['x-max-frame-bytes']};",
            f"pub const MAX_JSON_DEPTH: usize = {envelope['x-max-depth']};", ""]
    go = ["// Code generated by scripts/generate-protocol.py. DO NOT EDIT.", "package protocol", "", 'import "encoding/json"', "",
          f"const MaxFrameBytes = {envelope['x-max-frame-bytes']}",
          f"const MaxJSONDepth = {envelope['x-max-depth']}", ""]
    for name, schema in definitions.items():
        if "enum" in schema:
            rust += ["#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]", "pub enum " + name + " {"]
            go += ["type " + name + " string", "const ("]
            for value in schema["enum"]:
                rust += ['    #[serde(rename = "' + value + '")]', "    " + pascal(value) + ","]
                go += ["    " + name + pascal(value) + " " + name + " = " + json.dumps(value)]
            rust += ["}", ""]
            go += [")", ""]
            continue
        rust += ["#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]"]
        if schema.get("additionalProperties") is False:
            rust += ["#[serde(deny_unknown_fields)]"]
        rust += ["pub struct " + name + " {"]
        go += ["type " + name + " struct {"]
        for field, definition in schema.get("properties", {}).items():
            required = field in schema.get("required", [])
            rt, gt = type_of(definition, "rust"), type_of(definition, "go")
            if not required:
                rt = "Option<" + rt + ">"
                gt = "*" + gt
                rust += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
            rust_field = "r#type" if field == "type" else field
            rust += ["    pub " + rust_field + ": " + rt + ","]
            go += ["    " + pascal(field) + " " + gt + " `json:\"" + field + (",omitempty" if not required else "") + "\"`"]
        rust += ["}", ""]
        go += ["}", ""]
    schema_text = json.dumps(bundle, ensure_ascii=False, indent=2) + "\n"
    return {
        ROOT / "crates/dzc-protocol/src/wire/generated.rs": "\n".join(rust),
        ROOT / "clients/go/protocol/generated.go": "\n".join(go),
        ROOT / "crates/dzc-protocol/src/wire/schema.json": schema_text,
        ROOT / "clients/go/protocol/schema.json": schema_text,
        **metadata,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("regenerate protocol outputs: " + ", ".join(stale))


if __name__ == "__main__":
    main()
