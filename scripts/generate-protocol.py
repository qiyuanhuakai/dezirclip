"""Generate protocol values, settings metadata and an offline schema."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB_TYPES = (
    "DesktopProfileInfo", "EventKind", "RuntimeState", "EventData", "Event", "EventsResult",
    "PrivacyState", "HostMode", "ServiceStatus", "DesktopPageParams", "DesktopTagPageParams",
)
SWIFT_TYPES = (
    "ProtocolVersion", "ClientRole", "Method", "Permission", "RuntimeState", "HelloParams", "HelloResult",
    "WireErrorCode", "WireError", "EventKind", "EventData", "Event", "SubscribeParams", "EventsResult",
    "DesktopPageParams", "DesktopEntryParams", "DesktopEntry", "DesktopEntries",
    "BodySnapshot", "SnapshotReadParams", "SnapshotChunk", "WindowsPasteTarget", "DesktopCopyParams",
    "OperationResult",
)


def pascal(value):
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[._-]", value))


def type_of(schema, language):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if language == "rust" and "x-rust-type" in schema:
        return schema["x-rust-type"]
    kind = schema.get("type")
    if isinstance(kind, list):
        inner = type_of({**schema, "type": next(x for x in kind if x != "null")}, language)
        return "Option<" + inner + ">" if language == "rust" else "*" + inner
    if kind == "array":
        inner = type_of(schema["items"], language)
        return "Vec<" + inner + ">" if language == "rust" else "[]" + inner
    if kind == "integer":
        native = schema.get("x-rust-type", "i64")
        return {"u16": "uint16", "u32": "uint32", "u64": "uint64", "i64": "int64"}.get(native, "int64")
    return ({"string": "String", "boolean": "bool", "number": "f64"}.get(kind, "serde_json::Value")
            if language == "rust" else {"string": "string", "boolean": "bool", "number": "float64"}.get(kind, "json.RawMessage"))


def web_type(schema):
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[1]
        if name not in WEB_TYPES:
            raise ValueError(f"missing generated TypeScript dependency: {name}")
        return name
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema["type"]
    if isinstance(kind, list):
        return " | ".join(web_type({**schema, "type": option}) for option in kind)
    if kind == "array":
        return f"Array<{web_type(schema['items'])}>"
    return {"integer": "number", "boolean": "boolean", "string": "string", "null": "null"}[kind]


def web_values(definitions):
    lines = ["// Generated by scripts/generate-protocol.py; edit protocol/schema.", ""]
    for name in WEB_TYPES:
        schema = definitions[name]
        if schema["type"] != "object":
            lines += [f"export type {name} = {web_type(schema)};", ""]
            continue
        lines.append(f"export interface {name} {{")
        for field, definition in schema["properties"].items():
            suffix = "" if field in schema["required"] else "?"
            lines.append(f"    {field}{suffix}: {web_type(definition)};")
        lines += ["}", ""]
    return "\n".join(lines)


def swift_name(value):
    name = pascal(value)
    return name[0].lower() + name[1:]


def swift_type(schema):
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[1]
        if name not in SWIFT_TYPES:
            raise ValueError(f"missing generated Swift dependency: {name}")
        return name
    kind = schema["type"]
    if kind == "array":
        return f"[{swift_type(schema['items'])}]"
    if kind == "integer":
        return {"u16": "UInt16", "u32": "UInt32", "u64": "UInt64", "i64": "Int64"}[schema["x-rust-type"]]
    return {"string": "String", "boolean": "Bool"}[kind]


def swift_constraint(schema, value):
    """Only emit types whose schema constraints are enforced by the Swift mirror."""
    if "$ref" in schema:
        if set(schema) != {"$ref"}:
            raise ValueError(f"unsupported Swift reference keywords: {schema}")
        return []
    kind = schema["type"]
    allowed = {
        "string": {"minLength", "maxLength", "pattern"},
        "integer": {"minimum", "maximum", "not", "x-rust-type"},
        "array": {"items", "maxItems"},
        "boolean": set(),
    }[kind]
    if not set(schema) <= (allowed | {"type"}):
        raise ValueError(f"unsupported Swift field constraints: {schema}")
    integer = schema.get("x-rust-type")
    native = {
        "u16": (0, 2**16 - 1), "u32": (0, 2**32 - 1),
        "u64": (0, 2**64 - 1), "i64": (-2**63, 2**63 - 1),
    }.get(integer)
    checks = []
    if "minimum" in schema and schema["minimum"] > native[0]:
        checks.append(f"{value} >= {schema['minimum']}")
    if "maximum" in schema and schema["maximum"] < native[1]:
        checks.append(f"{value} <= {schema['maximum']}")
    if "not" in schema:
        excluded = schema["not"]
        if set(excluded) != {"const"} or type(excluded["const"]) is not int:
            raise ValueError(f"unsupported Swift integer exclusion: {schema}")
        checks.append(f"{value} != {excluded['const']}")
    if "minLength" in schema:
        checks.append(f"{value}.unicodeScalars.count >= {schema['minLength']}")
    if "maxLength" in schema:
        checks.append(f"{value}.unicodeScalars.count <= {schema['maxLength']}")
    if "maxItems" in schema:
        checks.append(f"{value}.count <= {schema['maxItems']}")
    if "pattern" in schema:
        checks.append(f"{value}.range(of: {json.dumps(schema['pattern'])}, options: .regularExpression) == ({value}.startIndex..<{value}.endIndex)")
    if "items" in schema:
        inner = swift_constraint(schema["items"], "$0")
        if inner:
            predicate = " && ".join(inner)
            checks.append(f"{value}.allSatisfy({{ {predicate} }})")
    return checks


def swift_values(definitions, envelope):
    lines = [
        "// Generated by scripts/generate-protocol.py; edit protocol/schema.",
        "import Foundation", "",
        "public enum WireLimits {",
        f"    public static let maximumFrameBytes = {envelope['x-max-frame-bytes']}",
        f"    public static let maximumJSONDepth = {envelope['x-max-depth']}",
        "}", "",
        "public struct InvalidWireField: Error, Equatable, Sendable {",
        "    public let field: String",
        "}", "",
        "private struct WireCodingKey: CodingKey {",
        "    let stringValue: String",
        "    var intValue: Int? { nil }",
        "    init?(stringValue: String) { self.stringValue = stringValue }",
        "    init?(intValue: Int) { return nil }",
        "}", "",
    ]
    for name in SWIFT_TYPES:
        schema = definitions[name]
        if "enum" in schema:
            lines.append(f"public enum {name}: String, Codable, Sendable {{")
            for value in schema["enum"]:
                case = swift_name(value)
                if case == "internal":
                    case = "`internal`"
                lines.append(f"    case {case} = {json.dumps(value)}")
            lines += ["}", ""]
            continue
        if schema["type"] != "object" or type(schema.get("additionalProperties")) is not bool:
            raise ValueError(f"unsupported Swift object constraints: {name}")
        if set(schema) != {"type", "properties", "required", "additionalProperties"}:
            raise ValueError(f"unsupported Swift schema keywords: {name}")
        strict = not schema["additionalProperties"]
        lines.append(f"public struct {name}: Codable, Equatable, Sendable {{")
        fields = [(wire, swift_name(wire), swift_type(prop), wire in schema["required"], prop)
                  for wire, prop in schema["properties"].items()]
        validation = [(wire, field, required, swift_constraint(prop, field))
                      for wire, field, _, required, prop in fields]
        validation = [entry for entry in validation if entry[3]]
        for _, field, kind, required, _ in fields:
            lines.append(f"    public let {field}: {kind}" + ("" if required else "?"))
        all_keys = ", CaseIterable" if strict else ""
        lines += ["", f"    private enum CodingKeys: String, CodingKey{all_keys} {{"]
        for wire, field, _, _, _ in fields:
            lines.append(f"        case {field} = {json.dumps(wire)}")
        lines += ["    }", "", "    public init("]
        params = [f"{field}: {kind}" + ("" if required else "? = nil")
                  for _, field, kind, required, _ in fields]
        lines += ["        " + ",\n        ".join(params), "    ) throws {"]
        for _, field, _, _, _ in fields:
            lines.append(f"        self.{field} = {field}")
        if validation:
            lines.append("        try validate()")
        lines += ["    }", "", "    public init(from decoder: Decoder) throws {"]
        if strict:
            lines += [
                "        let fields = try decoder.container(keyedBy: WireCodingKey.self)",
                "        let allowed = Set(CodingKeys.allCases.map(\\.stringValue))",
                "        if let unknown = fields.allKeys.first(where: { !allowed.contains($0.stringValue) }) {",
                f"            throw InvalidWireField(field: {json.dumps(name + '.')} + unknown.stringValue)",
                "        }",
            ]
        lines += ["        let container = try decoder.container(keyedBy: CodingKeys.self)", "        try self.init("]
        args = []
        for _, field, kind, required, _ in fields:
            decode = f"container.decode({kind}.self, forKey: .{field})"
            args.append(f"{field}: " + (decode if required else f"container.contains(.{field}) ? {decode} : nil"))
        lines += ["            " + ",\n            ".join(args), "        )", "    }"]
        if validation:
            lines += ["", "    private func validate() throws {"]
            for wire, field, required, bounds in validation:
                check = ", ".join(bounds)
                error = f"throw InvalidWireField(field: {json.dumps(name + '.' + wire)})"
                if required:
                    lines.append(f"        guard {check} else {{ {error} }}")
                else:
                    lines += [f"        if let {field} {{", f"            guard {check} else {{ {error} }}", "        }"]
            lines += ["    }"]
        lines += ["}", ""]
    return "\n".join(lines)


def settings_outputs(groups):
    rust = [
        "// Generated by scripts/generate-protocol.py; edit protocol/settings.catalog.json.",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct Setting {",
        "    pub key: &'static str,",
        "    pub group: &'static str,",
        "    pub kind: &'static str,",
        "    pub values: &'static [&'static str],",
        "    pub option_label_keys: &'static [(&'static str, &'static str)],",
        "    pub label_key: &'static str,",
        "    pub requires_restart: bool,",
        "    pub seed_default: Option<&'static str>,",
        "}", "",
    ]
    go = [
        "// Code generated by scripts/generate-protocol.py. Edit protocol/settings.catalog.json.",
        "package protocol", "",
        "type Setting struct {",
        "\tKey             string",
        "\tGroup           string",
        "\tKind            string",
        "\tValues          []string",
        "\tOptionLabelKeys map[string]string",
        "\tLabelKey        string",
        "\tRequiresRestart bool",
        "\tSeedDefault     *string",
        "}", "",
    ]
    ts = ["// Generated by scripts/generate-protocol.py; edit protocol/settings.catalog.json."]
    seen = set()
    for group, entries in groups.items():
        for entry in entries:
            key = entry["key"]
            label = entry["labelKey"]
            kind = entry["kind"]
            values = entry.get("values", [])
            option_labels = entry.get("optionLabelKeys", {})
            restart = entry["requiresRestart"]
            seed = entry.get("seedDefault")
            if key in seen or not re.fullmatch(r"app\.[a-z][a-z0-9_]*", key):
                raise ValueError(f"invalid or duplicate setting key: {key}")
            if not re.fullmatch(r"[a-z][a-z0-9_]*", label) or type(restart) is not bool:
                raise ValueError(f"invalid setting label or restart policy: {key}")
            if kind == "boolean" and not values:
                allowed = ("true", "false")
            elif kind == "enum" and values and all(isinstance(value, str) for value in values):
                allowed = values
            else:
                raise ValueError(f"invalid logical type or choices: {key}")
            if seed is not None and seed not in allowed:
                raise ValueError(f"invalid persisted default: {key}")
            if option_labels and (kind != "enum" or set(option_labels) != set(values)
                                  or not all(re.fullmatch(r"[a-z][a-z0-9_]*", label) for label in option_labels.values())):
                raise ValueError(f"invalid option labels: {key}")
            seen.add(key)
            stem = key.removeprefix("app.")
            rust_name = stem.upper()
            go_name = pascal(stem)
            ts_name = go_name[0].lower() + go_name[1:] + "Setting"
            value_literals = ", ".join(json.dumps(value) for value in values)
            rust_label_pairs = ", ".join(f"({json.dumps(value)}, {json.dumps(label)})" for value, label in option_labels.items())
            go_label_pairs = ", ".join(f"{json.dumps(value)}: {json.dumps(label)}" for value, label in option_labels.items())
            rust_seed = "None" if seed is None else f"Some({json.dumps(seed)})"
            rust += [
                f"pub const {rust_name}: Setting = Setting {{",
                f"    key: {json.dumps(key)},",
                f"    group: {json.dumps(group)},",
                f"    kind: {json.dumps(kind)},",
                f"    values: &[{value_literals}],",
                f"    option_label_keys: &[{rust_label_pairs}],",
                f"    label_key: {json.dumps(label)},",
                f"    requires_restart: {json.dumps(restart)},",
                f"    seed_default: {rust_seed},",
                "};", "",
            ]
            go += [
                f"const Setting{go_name} = {json.dumps(key)}",
                f"const Setting{go_name}Label = {json.dumps(label)}", "",
                f"func {go_name}Setting() Setting {{",
            ]
            if seed is not None:
                go.append(f"\tseed := {json.dumps(seed)}")
            go += [
                "\treturn Setting{",
                f"\t\tKey:             Setting{go_name},",
                f"\t\tGroup:           {json.dumps(group)},",
                f"\t\tKind:            {json.dumps(kind)},",
                f"\t\tValues:          " + ("nil," if not values else f"[]string{{{value_literals}}},"),
                "\t\tOptionLabelKeys: " + ("nil," if not option_labels else f"map[string]string{{{go_label_pairs}}},"),
                f"\t\tLabelKey:        Setting{go_name}Label,",
                f"\t\tRequiresRestart: {json.dumps(restart)},",
                "\t\tSeedDefault:     " + ("nil," if seed is None else "&seed,"),
                "\t}", "}", "",
            ]
            ts.append(f"export const {ts_name} = {json.dumps({**entry, 'group': group}, indent=4)} as const;")
    return {
        ROOT / "crates/dzc-protocol/src/settings.rs": "\n".join(rust),
        ROOT / "clients/go/protocol/settings.go": "\n".join(go),
        ROOT / "src/shared/protocol/settings.ts": "\n".join(ts) + "\n",
    }


def outputs():
    definitions = {}
    documents = []
    settings = json.loads((ROOT / "protocol/settings.catalog.json").read_text(encoding="utf-8"))
    metadata = settings_outputs(settings)
    for path in sorted((ROOT / "protocol/schema").glob("*.schema.json")):
        document = json.loads(path.read_text(encoding="utf-8"))
        documents.append(document)
        for name, schema in document["$defs"].items():
            if name in definitions:
                raise ValueError("duplicate protocol definition: " + name)
            definitions[name] = schema

    def local_refs(value):
        if isinstance(value, dict):
            result = {}
            for key, child in value.items():
                if key == "$ref":
                    if not child.startswith("https://dezirclip.local/protocol/v1/") or "#/$defs/" not in child:
                        raise ValueError("nonlocal protocol reference: " + child)
                    target = child.rsplit("/", 1)[1]
                    if target not in definitions:
                        raise ValueError("unknown protocol definition: " + target)
                    result[key] = "#/$defs/" + target
                elif key == "x-settings-catalog-keys":
                    if "enum" not in value:
                        raise ValueError("settings catalog requires a schema enum")
                elif key == "enum" and "x-settings-catalog-keys" in value:
                    groups = value["x-settings-catalog-keys"]
                    if not isinstance(groups, list) or not groups or len(set(groups)) != len(groups):
                        raise ValueError("settings schema requires unique catalog groups")
                    registered = [entry["key"] for group in groups for entry in settings[group]]
                    if set(registered).intersection(child):
                        raise ValueError("catalog setting is also registered directly in the schema")
                    result[key] = child + registered
                else:
                    result[key] = local_refs(child)
            return result
        if isinstance(value, list):
            return [local_refs(child) for child in value]
        return value

    envelope = next(doc for doc in documents if doc["$id"].endswith("/envelope.schema.json"))
    bundle = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": local_refs(definitions)}
    rust = ["// Generated by scripts/generate-protocol.py; edit protocol/schema instead.",
            "use serde::{Deserialize, Serialize};", "",
            f"pub const MAX_FRAME_BYTES: usize = {envelope['x-max-frame-bytes']};",
            f"pub const MAX_JSON_DEPTH: usize = {envelope['x-max-depth']};", ""]
    go = ["// Code generated by scripts/generate-protocol.py. DO NOT EDIT.", "package protocol", "", 'import "encoding/json"', "",
          f"const MaxFrameBytes = {envelope['x-max-frame-bytes']}",
          f"const MaxJSONDepth = {envelope['x-max-depth']}", ""]
    for name, schema in definitions.items():
        if "enum" in schema:
            rust += ["#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]", "pub enum " + name + " {"]
            go += ["type " + name + " string", "const ("]
            for value in schema["enum"]:
                rust += ['    #[serde(rename = "' + value + '")]', "    " + pascal(value) + ","]
                go += ["    " + name + pascal(value) + " " + name + " = " + json.dumps(value)]
            rust += ["}", ""]
            go += [")", ""]
            continue
        rust += ["#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]"]
        if schema.get("additionalProperties") is False:
            rust += ["#[serde(deny_unknown_fields)]"]
        rust += ["pub struct " + name + " {"]
        go += ["type " + name + " struct {"]
        for field, definition in schema.get("properties", {}).items():
            required = field in schema.get("required", [])
            rt, gt = type_of(definition, "rust"), type_of(definition, "go")
            if not required:
                rt = "Option<" + rt + ">"
                gt = "*" + gt
                rust += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
            rust_field = "r#type" if field == "type" else field
            rust += ["    pub " + rust_field + ": " + rt + ","]
            go += ["    " + pascal(field) + " " + gt + " `json:\"" + field + (",omitempty" if not required else "") + "\"`"]
        rust += ["}", ""]
        go += ["}", ""]
    schema_text = json.dumps(bundle, ensure_ascii=False, indent=2) + "\n"
    return {
        ROOT / "crates/dzc-protocol/src/wire/generated.rs": "\n".join(rust),
        ROOT / "clients/go/protocol/generated.go": "\n".join(go),
        ROOT / "crates/dzc-protocol/src/wire/schema.json": schema_text,
        ROOT / "clients/go/protocol/schema.json": schema_text,
        ROOT / "src/shared/protocol/wire.ts": web_values(definitions),
        ROOT / "clients/swift/Sources/DzcProtocol/Generated.swift": swift_values(definitions, envelope),
        **metadata,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("regenerate protocol outputs: " + ", ".join(stale))


if __name__ == "__main__":
    main()
