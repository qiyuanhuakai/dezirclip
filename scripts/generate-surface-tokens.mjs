import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'));
const typography = JSON.parse(readFileSync(resolve(root, 'design/typography.json'), 'utf8'));
const colors = ['background', 'panel', 'text', 'muted', 'accent', 'selected', 'border'];
const sizes = ['radius', 'padding', 'gap', 'rowHeight', 'fontSize', 'searchHeight', 'transitionMs'];
const capital = value => value[0].toUpperCase() + value.slice(1);
const kebab = value => value.replace(/[A-Z]/g, char => `-${char.toLowerCase()}`);
if (tokens.schemaVersion !== 1 || typography.schemaVersion !== 1) throw new Error('Unsupported design token schema');
for (const mode of ['light', 'dark']) {
  for (const name of colors) if (!/^#[0-9a-f]{6}$/i.test(tokens[mode]?.[name])) throw new Error(`Invalid ${mode} ${name}`);
}
for (const name of sizes) if (!Number.isSafeInteger(tokens[name]) || tokens[name] < 0 || tokens[name] > 1000) throw new Error(`Invalid ${name}`);
if (!Array.isArray(typography.families) || !typography.families.length
  || typography.families.some(value => typeof value !== 'string' || !/^[A-Za-z0-9 -]+$/.test(value))
  || typography.fallback !== 'sans-serif' || tokens.transitionCurve !== 'ease-out') throw new Error('Invalid surface typography or transition');
const families = typography.families.map(value => JSON.stringify(value)).join(', ');
for (const name of ['regularWeight', 'emphasisWeight']) {
  if (!Number.isInteger(typography[name]) || typography[name] < 100 || typography[name] > 900 || typography[name] % 100) throw new Error(`Invalid ${name}`);
}
const css = `/* Generated by pnpm run surface:tokens; edit design/*.json. */\n:root {\n${colors.map(name => `  --dzc-surface-${name}: ${tokens.light[name]};`).join('\n')}\n${sizes.map(name => `  --dzc-surface-${kebab(name)}: ${tokens[name]}${name === 'transitionMs' ? 'ms' : 'px'};`).join('\n')}\n  --dzc-surface-font-family: ${families}, ${typography.fallback};\n  --dzc-surface-transition-curve: ${tokens.transitionCurve};\n}\n:root.dark-mode, body.dark-mode {\n${colors.map(name => `  --dzc-surface-${name}: ${tokens.dark[name]};`).join('\n')}\n}\n`;
const go = `// Code generated by pnpm run surface:tokens; DO NOT EDIT.\npackage theme\n\ntype Tokens struct {\n${colors.map(name => `\t${capital(name)} string`).join('\n')}\n${sizes.map(name => `\t${capital(name)} int`).join('\n')}\n\tFontFamilies []string\n\tRegularWeight int\n\tEmphasisWeight int\n}\n\nfunc Select(mode string) Tokens {\n\tt := Tokens{\n${colors.map(name => `\t\t${capital(name)}: ${JSON.stringify(tokens.light[name])},`).join('\n')}\n${sizes.map(name => `\t\t${capital(name)}: ${tokens[name]},`).join('\n')}\n\t\tFontFamilies: []string{${families}},\n\t\tRegularWeight: ${typography.regularWeight},\n\t\tEmphasisWeight: ${typography.emphasisWeight},\n\t}\n\tif mode == "dark" {\n${colors.map(name => `\t\tt.${capital(name)} = ${JSON.stringify(tokens.dark[name])}`).join('\n')}\n\t}\n\treturn t\n}\n`;
for (const [relative, contents] of [
  ['src/styles/tokens/surface.generated.css', css],
  ['frontends/dzc-surface/theme/tokens_generated.go', go],
]) {
  const path = resolve(root, relative);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== contents) throw new Error(`Generated surface tokens differ: ${relative}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
  }
}
