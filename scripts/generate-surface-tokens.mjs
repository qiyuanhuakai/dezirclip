import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BUILTIN_THEMES } from '@deziro/ui-react/themes';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'));
const typography = JSON.parse(readFileSync(resolve(root, 'design/typography.json'), 'utf8'));
const colors = ['background', 'panel', 'text', 'muted', 'accent', 'selected', 'border'];
const sizes = ['radius', 'padding', 'gap', 'rowHeight', 'fontSize', 'searchHeight', 'transitionMs'];
const kebab = value => value.replace(/[A-Z]/g, char => `-${char.toLowerCase()}`);
if (tokens.schemaVersion !== 1 || typography.schemaVersion !== 1) throw new Error('Unsupported design token schema');
for (const mode of ['light', 'dark']) {
  for (const name of colors) if (!/^#[0-9a-f]{6}$/i.test(tokens[mode]?.[name])) throw new Error(`Invalid ${mode} ${name}`);
}
for (const name of sizes) if (!Number.isSafeInteger(tokens[name]) || tokens[name] < 0 || tokens[name] > 1000) throw new Error(`Invalid ${name}`);
if (!Array.isArray(typography.families) || !typography.families.length
  || typography.families.some(value => typeof value !== 'string' || !/^[A-Za-z0-9 -]+$/.test(value))
  || typography.fallback !== 'sans-serif' || tokens.transitionCurve !== 'ease-out') throw new Error('Invalid surface typography or transition');
const families = typography.families.map(value => JSON.stringify(value)).join(', ');
for (const name of ['regularWeight', 'emphasisWeight']) {
  if (!Number.isInteger(typography[name]) || typography[name] < 100 || typography[name] > 900 || typography[name] % 100) throw new Error(`Invalid ${name}`);
}
const css = `/* Generated by pnpm run surface:tokens; edit design/*.json. */\n:root {\n${colors.map(name => `  --dzc-surface-${name}: ${tokens.light[name]};`).join('\n')}\n${sizes.map(name => `  --dzc-surface-${kebab(name)}: ${tokens[name]}${name === 'transitionMs' ? 'ms' : 'px'};`).join('\n')}\n  --dzc-surface-font-family: ${families}, ${typography.fallback};\n  --dzc-surface-transition-curve: ${tokens.transitionCurve};\n}\n:root.dark-mode, body.dark-mode {\n${colors.map(name => `  --dzc-surface-${name}: ${tokens.dark[name]};`).join('\n')}\n}\n`;
const installed = new URL(import.meta.resolve('@deziro/ui-react/styles/tokens/surface.generated.css'));
if (readFileSync(installed, 'utf8') !== css) {
  throw new Error('Published Deziro UI tokens differ from the DezirClip design contract');
}

const themeCatalog = JSON.parse(readFileSync(resolve(root, 'design/themes.json'), 'utf8'));
const { themes } = themeCatalog;
const ids = themes.map(theme => theme.id);
if (!ids.includes(themeCatalog.default) || new Set(ids).size !== ids.length
    || JSON.stringify(ids) !== JSON.stringify(BUILTIN_THEMES)) {
  throw new Error('Published Deziro UI themes differ from the DezirClip theme catalog');
}
for (const { id, labelKey, cssEntry, windowsBackdrop } of themes) {
  if (!/^[a-z][a-z-]*$/.test(id) || !/^[a-z][a-z_]*$/.test(labelKey)
      || cssEntry !== `styles/themes/${id}.css`
      || (windowsBackdrop !== undefined && !['mica', 'acrylic'].includes(windowsBackdrop))) {
    throw new Error(`Invalid theme entry: ${id}`);
  }
  readFileSync(new URL(import.meta.resolve(`@deziro/ui-react/${cssEntry}`)));
}
const literal = JSON.stringify;
const backdrops = themes.filter(theme => theme.windowsBackdrop);
const rust = [
  '// Generated by scripts/generate-surface-tokens.mjs. Edit design/themes.json.',
  `pub const DEFAULT_BUILTIN_THEME: &str = ${literal(themeCatalog.default)};`,
  `pub const BUILTIN_THEMES: &[&str] = &[${ids.map(id => literal(id)).join(', ')}];`,
  '',
  'pub fn builtin_windows_backdrop(theme: &str) -> Option<&\'static str> {',
  '    match theme {',
  ...backdrops.map(({ id, windowsBackdrop }) => `        ${literal(id)} => Some(${literal(windowsBackdrop)}),`),
  '        _ => None,',
  '    }',
  '}',
  '',
].join('\n');
const go = [
  '// Code generated by scripts/generate-surface-tokens.mjs. Edit design/themes.json.',
  'package model',
  '',
  `const DefaultBuiltinTheme = ${literal(themeCatalog.default)}`,
  '',
  'type BuiltinTheme struct {',
  '\tID       string',
  '\tLabelKey string',
  '}',
  '',
  'func BuiltinThemes() []BuiltinTheme {',
  '\treturn []BuiltinTheme{',
  ...themes.map(({ id, labelKey }) => `\t\t{ID: ${literal(id)}, LabelKey: ${literal(labelKey)}},`),
  '\t}',
  '}',
  '',
  'func BuiltinWindowsBackdrop(theme string) string {',
  '\tswitch theme {',
  ...backdrops.flatMap(({ id, windowsBackdrop }) => [`\tcase ${literal(id)}:`, `\t\treturn ${literal(windowsBackdrop)}`]),
  '\tdefault:',
  '\t\treturn ""',
  '\t}',
  '}',
  '',
].join('\n');
for (const [file, value] of [
  ['crates/dzc-core/src/domain/builtin_themes.rs', rust],
  ['frontends/dzc-surface/internal/model/themes.go', go],
]) {
  const path = resolve(root, file);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== value) throw new Error(`Theme catalog output is stale: ${file}`);
  } else {
    writeFileSync(path, value);
  }
}
