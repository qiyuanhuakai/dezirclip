//! The Darwin helper owns pasteboard access on its process main thread.
use dzc_core::{
    capture::{
        CaptureData, CaptureFailure, CaptureReadRequest, CaptureReader, CaptureStage,
        PrivacyHintAvailability, PrivacyPreflight,
    },
    ports::PrivacyHint,
};
use objc2::rc::{Retained, autoreleasepool};
use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
use objc2_foundation::NSString;
use std::{io, marker::PhantomData, rc::Rc};

pub struct MainThreadClipboard {
    pasteboard: Retained<NSPasteboard>,
    _thread: PhantomData<Rc<()>>,
}

impl MainThreadClipboard {
    pub fn open() -> io::Result<Self> {
        if unsafe { libc::pthread_main_np() } != 1 {
            return Err(io::Error::new(
                io::ErrorKind::Unsupported,
                "Darwin clipboard requires the main thread",
            ));
        }
        Ok(Self {
            pasteboard: autoreleasepool(|_| NSPasteboard::generalPasteboard()),
            _thread: PhantomData,
        })
    }

    pub fn change_count(&self) -> isize {
        autoreleasepool(|_| self.pasteboard.changeCount())
    }

    pub fn write_text(&mut self, text: &str) -> io::Result<()> {
        self.write_text_owned(text).map(|_| ())
    }

    /// The ownership count returned by clearContents identifies this write,
    /// even if a different process takes the pasteboard again immediately.
    pub fn write_text_owned(&mut self, text: &str) -> io::Result<isize> {
        autoreleasepool(|_| {
            let count = self.pasteboard.clearContents();
            let value = NSString::from_str(text);
            if self
                .pasteboard
                .setString_forType(&value, unsafe { NSPasteboardTypeString })
            {
                Ok(count)
            } else {
                Err(io::Error::other("Darwin clipboard text write failed"))
            }
        })
    }

    pub fn read_text(&mut self) -> io::Result<String> {
        autoreleasepool(|_| {
            self.pasteboard
                .stringForType(unsafe { NSPasteboardTypeString })
                .map(|value| value.to_string())
                .ok_or_else(|| {
                    io::Error::new(io::ErrorKind::NotFound, "Darwin clipboard text unavailable")
                })
        })
    }

    pub fn capture_reader(&self, change_count: isize) -> DarwinTextReader<'_> {
        DarwinTextReader {
            clipboard: self,
            change_count,
            readable: false,
        }
    }
}

pub struct DarwinTextReader<'a> {
    clipboard: &'a MainThreadClipboard,
    change_count: isize,
    readable: bool,
}

impl CaptureReader for DarwinTextReader<'_> {
    fn preflight_privacy(&mut self) -> Result<PrivacyPreflight, CaptureFailure> {
        autoreleasepool(|_| {
            if self.clipboard.pasteboard.changeCount() != self.change_count {
                return Err(selection_changed());
            }
            let Some(types) = self.clipboard.pasteboard.types() else {
                self.readable = false;
                return Ok(PrivacyPreflight::default());
            };
            let mut hints = Vec::new();
            let mut has_text = false;
            let mut has_file = false;
            let text_type = unsafe { NSPasteboardTypeString }.to_string();
            for format in types.iter() {
                let format = format.to_string();
                match format.as_str() {
                    "org.nspasteboard.ConcealedType" | "com.agilebits.onepassword" => {
                        hints.push(PrivacyHint::Sensitive)
                    }
                    "org.nspasteboard.TransientType"
                    | "org.nspasteboard.AutoGeneratedType"
                    | "de.petermaurer.TransientPasteboardType"
                    | "com.typeit4me.clipping"
                    | "Pasteboard generator type" => hints.push(PrivacyHint::ExcludeFromHistory),
                    "public.file-url" => has_file = true,
                    _ => has_text |= format == text_type,
                }
            }
            self.readable = has_text && !has_file && hints.is_empty();
            Ok(PrivacyPreflight {
                hints,
                availability: PrivacyHintAvailability::Checked,
                selection_id: Some(self.change_count as u64),
            })
        })
    }

    fn selection_id(&self) -> Option<u64> {
        Some(self.clipboard.change_count() as u64)
    }

    fn read(&mut self, _: CaptureReadRequest) -> Result<Option<CaptureData>, CaptureFailure> {
        if !self.readable {
            return Ok(None);
        }
        autoreleasepool(|_| {
            if self.clipboard.pasteboard.changeCount() != self.change_count {
                return Err(selection_changed());
            }
            let Some(text) = self
                .clipboard
                .pasteboard
                .stringForType(unsafe { NSPasteboardTypeString })
            else {
                return Ok(None);
            };
            if self.clipboard.pasteboard.changeCount() != self.change_count {
                return Err(selection_changed());
            }
            if text.length() > 10 * 1024 * 1024 {
                return Err(CaptureFailure {
                    stage: CaptureStage::Read,
                    code: "ClipboardTextTooLarge".into(),
                });
            }
            Ok(Some(CaptureData::Text(text.to_string())))
        })
    }
}

fn selection_changed() -> CaptureFailure {
    CaptureFailure {
        stage: CaptureStage::Read,
        code: "ClipboardSelectionChanged".into(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn worker_cannot_open_the_darwin_clipboard() {
        let error = std::thread::spawn(|| MainThreadClipboard::open().err().unwrap().kind())
            .join()
            .unwrap();
        assert_eq!(error, io::ErrorKind::Unsupported);
    }
}
